const TOKENS = Object.keys(VERBS).sort((a, b) => b.length - a.length);

/* ────────────────────────────────────────────────────────────────────
 *  הכלל הכללי — למה הוא נחוץ
 * ────────────────────────────────────────────────────────────────────
 *  המילון שלמעלה הוא רשימה ידנית, וכל ניסוח חדש שנכתב בשיעור ("תספור/י",
 *  "יודע/את") נופל ממנו — והילד רואה על המסך לוכסן במקום מילה. סריקה על
 *  שיעורי-הזהב מצאה 228 אסימונים כאלה. לכן: המילון נשאר לחריגים, וכל
 *  השאר נפתר בכלל מורפולוגי.
 *
 *  הצורה היא תמיד X/Y:
 *    • Y מילה שלמה  ("קפוץ/קפצי")  → זכר X, נקבה Y.
 *    • Y סיומת קצרה ("תוריד/י")   → נקבה = X + Y, אחרי החזרת אות-סופית
 *      לצורתה הרגילה (צריך/ה → צריכה, מקצוען/ית → מקצוענית).
 *    • X שכבר נגמר ב-Y ("רואה/ה") → הצורות זהות.
 */

const FINAL_TO_REGULAR = { ך: "כ", ם: "מ", ן: "נ", ף: "פ", ץ: "צ" };
const HEB = "א-ת";

/** X/Y → [זכר, נקבה]. */
function splitSlashForm(male, femIn) {
  let fem = femIn;
  if (!male || !fem) return null;

  // Y מילה שלמה בפני עצמה — פשוט מחליפים. אם X נושא ו״ו-חיבור ו-Y לא,
  // היא שייכת לשתי הצורות ("ותשווה/תשווי" → ותשווה · ותשווי).
  if (fem.length >= 3) {
    const f = male[0] === "ו" && fem[0] !== "ו" ? "ו" + fem : fem;
    return [male, f];
  }

  // X כבר מסתיים ב-Y ("רואה/ה") — אין מה להוסיף
  if (male.endsWith(fem)) return [male, male];

  // צורה מתקצרת: Y הוא ראשיתו של X ("אתה/את") — הנקבה קצרה מהזכר, לא סיומת
  if (fem.length >= 2 && male.startsWith(fem)) return [male, fem];
  // ...וגם כשיש תחילית ("שאתה/את", "ואתה/את") — הזכר הוא הנקבה ועוד ה״א
  if (fem.length >= 2 && male.endsWith(fem + "ה")) return [male, male.slice(0, -1)];

  // "יודע/את" — הכותב התכוון לסיומת הנקבה ת׳, לא למילה "את"
  if (fem === "את") fem = "ת";

  // סיומת: מחזירים אות-סופית לצורתה הרגילה לפני ההדבקה
  const last = male[male.length - 1];
  let stem = FINAL_TO_REGULAR[last] ? male.slice(0, -1) + FINAL_TO_REGULAR[last] : male;
  // ...ואם הסיומת פותחת באותה אות שהגזע נגמר בה, לא מכפילים אותה
  // ("תמשיך/כי" → תמשיכי, ולא תמשיככי)
  if (stem[stem.length - 1] === fem[0]) stem = stem.slice(0, -1);
  return [male, stem + fem];
}

const SLASH_RE = new RegExp(`([${HEB}]{2,})\\/([${HEB}]{1,})`, "g");

function genderize(text, gender) {
  if (text == null) return text;
  const female = gender === "female";
  const idx = female ? 1 : 0;
  let out = String(text);
  // קודם החריגים מהמילון — הם מדויקים יותר מכל כלל
  for (const tok of TOKENS) {
    if (out.indexOf(tok) !== -1) out = out.split(tok).join(VERBS[tok][idx]);
  }
  // ואז הכלל הכללי, על כל מה שנשאר
  return out.replace(SLASH_RE, (m, a, b) => {
    const pair = splitSlashForm(a, b);
    return pair ? pair[idx] : m;
  });
}

// ממגדר אובייקט שאלה (טקסט, רמזים, הסבר) במקום
function genderizeProblem(problem, gender) {
  if (!problem) return problem;
  if (typeof problem.text === "string") problem.text = genderize(problem.text, gender);
  if (typeof problem.explanation === "string") problem.explanation = genderize(problem.explanation, gender);
  if (Array.isArray(problem.hints)) problem.hints = problem.hints.map((h) => genderize(h, gender));
  return problem;
}

module.exports = { genderize, genderizeProblem };
