/* ── נפילה-אחורה: בונים שיטה מה-hints הקיימים ─────────────────────── */

/**
 * ה-hints בבנק טובים — הם מכילים שיטה אמיתית ("אפשר לפרק לעשרות ויחידות").
 * כשאין חוק מתאים, מרכיבים מהם הסבר זורם במקום להחזיר את התשובה.
 */
function fromHints(q) {
  const hints = (Array.isArray(q.hints) ? q.hints : [])
    .map((h) => String(h || "").trim())
    .filter((h) => h && !h.includes(String(q.answer)) && /[֐-׿]/.test(h) && h.split(/\s+/).length >= 3)
    // רמז שכבר פותר תרגיל ("42 − 31 = 11") עושה את העבודה במקום הילד — לא נכנס להסבר.
    .filter((h) => !/\d+(?:\.\d+)?\s*[+\-−×*÷:]\s*\d+(?:\.\d+)?\s*=\s*\d/.test(h));
  if (!hints.length) return null;
  const body = hints.map((h) => h.replace(/\s*[.!]+$/, "")).join(". ") + ".";
  return body;
}

