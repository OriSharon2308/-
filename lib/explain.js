function addMethod(a, b) {
  const { t, u } = tensUnits(b);
  if (b === 0 || a === 0) return `כשמוסיפים 0 המספר לא משתנה בכלל — הוא נשאר כמו שהיה.`;
  if (a + b <= 20) return `אפשר להתחיל מ-${a} ולספור ${b} קדימה: ${a}, ואחר-כך עוד ${b} צעדים.`;
  if (t && u) return `נוח לפרק את ${b} לעשרות ואחדות: ${t} ועוד ${u}. קודם מחברים ${a} + ${t}, ואחר-כך מוסיפים את ה-${u} שנשארו.`;
  if (t) return `${b} הוא עשרות שלמות, אז מוסיפים ${t / 10} עשרות ל-${a} — העשרות גדלות והאחדות לא נוגעים בהן.`;
  return `אפשר להתחיל מ-${a} ולספור ${b} קדימה.`;
}

function subMethod(a, b) {
  const { t, u } = tensUnits(b);
  if (b === 0) return `כשמורידים 0 לא מורידים כלום — המספר נשאר כמו שהיה.`;
  if (a - b >= 0 && b <= 5) return `אפשר להתחיל מ-${a} ולספור ${b} אחורה, צעד-צעד.`;
  if (t && u) return `נוח לפרק את ${b} לעשרות ואחדות: ${t} ועוד ${u}. קודם מורידים את ${t} מ-${a}, ואחר-כך עוד ${u}.`;
  if (t) return `${b} הוא עשרות שלמות, אז מורידים ${t / 10} עשרות מ-${a} — רק ספרת העשרות משתנה.`;
  return `אפשר לספור אחורה מ-${a}, או לחשוב: מה צריך להוסיף ל-${b} כדי להגיע ל-${a}?`;
}

function mulMethod(a, b) {
  if (b === 0 || a === 0) return `כל מספר כפול 0 נותן 0 — אין אף קבוצה.`;
  if (b === 1) return `כל מספר כפול 1 נשאר הוא עצמו — יש בדיוק קבוצה אחת.`;
  if (a === 1) return `1 כפול כל מספר נותן את המספר עצמו.`;
  if (b === 10 || a === 10) {
    const o = b === 10 ? a : b;
    return `כפל ב-10 זה פשוט: לוקחים את ${o} ומוסיפים אפס בסוף — כל ספרה זזה בית אחד שמאלה.`;
  }
  if (b === 2 || a === 2) {
    const o = b === 2 ? a : b;
    return `כפל ב-2 זה פשוט לקחת את ${o} פעמיים — ${o} ועוד ${o}.`;
  }
  if (b === 5 || a === 5) {
    const o = b === 5 ? a : b;
    return `כפל ב-5 זה חצי מהכפל ב-10: קודם ${o} × 10, ואז חצי מזה.`;
  }
  if (b === 9 || a === 9) {
    const o = b === 9 ? a : b;
    return `טריק ל-9: 9 זה 10 פחות 1. קודם ${o} × 10, ואז מורידים ${o} אחד.`;
  }
  if (b === 4 || a === 4) {
    const o = b === 4 ? a : b;
    return `כפל ב-4 זה כפול, ואז כפול שוב: קודם ${o} × 2, ואת התוצאה שוב כפול 2.`;
  }
  const big = Math.max(a, b), small = Math.min(a, b);
  const { t, u } = tensUnits(big);
  if (t && u && small <= 12) {
    return `מפרקים את ${big} ל-${t} ועוד ${u} (זה חוק הפילוג). מחשבים ${t} × ${small}, אחר-כך ${u} × ${small}, ומחברים את שתי התוצאות.`;
  }
  return `כפל זה קבוצות שוות: ${small} קבוצות של ${big} בכל אחת. אפשר לפרק את ${big} לעשרות ואחדות, לכפול כל חלק בנפרד, ולחבר.`;
}

function divMethod(a, b) {
  if (b === 1) return `חילוק ב-1 לא משנה כלום — המספר נשאר הוא עצמו.`;
  if (a === b) return `כשמחלקים מספר בעצמו מקבלים תמיד 1 — יש בדיוק קבוצה אחת.`;
  if (b === 10) return `חילוק ב-10 זה להוריד אפס אחד מהסוף — כל ספרה זזה בית אחד ימינה.`;
  if (b === 2) return `חילוק ב-2 זה למצוא חצי: לחלק את ${a} לשני חלקים שווים.`;
  if (b === 5) return `חילוק ב-5 — שאל/שאלי את עצמך: כמה פעמים 5 נכנס ב-${a}? אפשר לספור בקפיצות של 5.`;
  const { t, u } = tensUnits(a);
  if (t && u && isInt(t / b)) {
    return `חילוק זה כפל שהולך אחורה — חפש/חפשי איזה מספר כפול ${b} נותן ${a}. אפשר גם לפרק: ${t} ÷ ${b} ואחר-כך ${u} ÷ ${b}, ולחבר.`;
  }
  return `חילוק זה כפל שהולך אחורה: חפש/חפשי איזה מספר כפול ${b} נותן ${a}. לוח הכפל עוזר כאן.`;
}

